  addressSuggestions:query=>ipcRenderer.invoke('browser:address-suggestions',query),
  history: (action, payload) => ipcRenderer.invoke('browser:history', action, payload),
  togglePictureInPicture: () => ipcRenderer.invoke('browser:toggle-pip'),
  searchMusic: (query) => ipcRenderer.invoke('browser:search-music', query),
  getMusicFavorites: () => ipcRenderer.invoke('browser:get-music-favorites'),
  toggleMusicFavorite: (track) => ipcRenderer.invoke('browser:toggle-music-favorite', track),
  isMusicFavorited: (id) => ipcRenderer.invoke('browser:is-music-favorited', id),
  cacheMusicTrack: (track) => ipcRenderer.invoke('browser:cache-music-track', track),
  removeCachedMusic: (id) => ipcRenderer.invoke('browser:remove-cached-music', id),
  musicPlay: (track) => ipcRenderer.invoke('browser:music-play', track),
  musicPause: () => ipcRenderer.invoke('browser:music-pause'),
  musicResume: () => ipcRenderer.invoke('browser:music-resume'),
  musicSeek: (seconds) => ipcRenderer.invoke('browser:music-seek', seconds),
