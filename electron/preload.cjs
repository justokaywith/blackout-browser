  toggleProtectionMenu: (anchorBounds) => ipcRenderer.invoke('browser:toggle-protection-menu', anchorBounds),
  toggleExtensionsMenu: (anchorBounds, pinnedIds) => ipcRenderer.invoke('browser:toggle-extensions-menu', anchorBounds, pinnedIds),
  toggleDownloadsMenu: (anchorBounds) => ipcRenderer.invoke('browser:toggle-downloads-menu', anchorBounds),
  toggleMusicPopup: (anchorBounds) => ipcRenderer.invoke('browser:toggle-music-popup', anchorBounds),
  getDownloads: () => ipcRenderer.invoke('browser:get-downloads'),
  runtimeInfo:()=>ipcRenderer.invoke('browser:runtime-info'),
  devicePolicy: value => ipcRenderer.invoke('browser:device-policy', value),
  notificationSettings: value => ipcRenderer.invoke('browser:notification-settings', value),
