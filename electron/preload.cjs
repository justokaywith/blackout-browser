  tabGroup: (action, payload) => ipcRenderer.invoke('browser:tab-group', action, payload),
  favorites: (action, payload) => ipcRenderer.invoke('browser:favorites', action, payload),
  showAppMenu: () => ipcRenderer.invoke('browser:app-menu'),
  setBookmarksBar: (visible) => ipcRenderer.invoke('browser:set-bookmarks-bar', visible),
  setUiAppearance: (appearance) => ipcRenderer.invoke('browser:set-ui-appearance', appearance),
  getUiAppearance: () => ipcRenderer.invoke('browser:get-ui-appearance'),
  bookmarkContextMenu: (item) => ipcRenderer.invoke('browser:bookmark-context-menu', item),
  windowAction: (action) => ipcRenderer.invoke('browser:window-action', action),
  reportCrash: (data) => ipcRenderer.invoke('browser:report-crash', data),
  setProtectionMode: (mode) => ipcRenderer.invoke('browser:set-protection-mode', mode),
  getProtectionMode: () => ipcRenderer.invoke('browser:get-protection-mode'),
  setProxy: (config) => ipcRenderer.invoke('browser:set-proxy', config),
