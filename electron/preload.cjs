  openDownload: (filePath) => ipcRenderer.invoke('browser:open-download', filePath),
  cancelDownload: (id) => ipcRenderer.invoke('browser:cancel-download', id),
  openDownloadsFolder: () => ipcRenderer.invoke('browser:open-downloads-folder'),
  getDownloadsPath: () => ipcRenderer.invoke('browser:get-downloads-path'),
